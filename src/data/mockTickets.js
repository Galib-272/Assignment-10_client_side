/** Quick lookup by ID (matches 'mock-1', '1', etc.) */
export const getMockTicketById = (id) => {
  if (!id) return null;
  const strId = String(id).toLowerCase();
  return (
    MOCK_TICKETS.find(
      (t) =>
        t._id.toLowerCase() === strId ||
        t._id.replace("mock-", "") === strId.replace("mock-", "")
    ) || null
  );
};

